import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const distDir = path.join(root, "dist");

function readConfig() {
  const filePath = path.join(root, "deploy.config.json");
  const file = JSON.parse(fs.readFileSync(filePath, "utf8"));
  const fromEnv = String(process.env.RAILWAY_API_URL || process.env.PORTAL_API_BASE || "")
    .trim()
    .replace(/\/api\/?$/, "");

  const fromFile = String(file.railwayOrigin || "")
    .trim()
    .replace(/\/api\/?$/, "")
    .replace(/\/$/, "");

  return (fromEnv || fromFile).replace(/\/$/, "");
}

const railwayOrigin = readConfig();
const onPagesOrVercel = Boolean(process.env.CF_PAGES || process.env.VERCEL);

if (onPagesOrVercel && !railwayOrigin) {
  console.error(
    "Set railwayOrigin in deploy.config.json (then push) or RAILWAY_API_URL on Cloudflare Pages."
  );
  process.exit(1);
}

const apiConfigPath = path.join(root, "portal", "api-config.js");
const useDirectApi =
  process.env.PORTAL_USE_DIRECT_API === "true" ||
  process.env.CF_USE_DIRECT_API === "true" ||
  process.env.VERCEL_USE_DIRECT_API === "true";
const productionApiBase = useDirectApi && railwayOrigin ? `${railwayOrigin}/api` : "";
const productionComment = productionApiBase
  ? "direct Railway"
  : "/api (Cloudflare Pages Function → Railway)";

const apiConfigBody = `// Generated by scripts/sync-deploy-config.js.
// On this LAN/localhost, talk to the local portal-server. On Cloudflare Pages, use ${productionComment}.
(function () {
  var host = typeof location !== "undefined" ? location.hostname : "";
  var port = typeof location !== "undefined" ? location.port : "";

  function isDeployedHost(h) {
    return (
      /(^|\\.)gzlawfirm\\.net$/i.test(h) ||
      /(^|\\.)pages\\.dev$/i.test(h) ||
      /(^|\\.)workers\\.dev$/i.test(h) ||
      /(^|\\.)vercel\\.app$/i.test(h) ||
      /(^|\\.)railway\\.app$/i.test(h)
    );
  }

  if (host && !isDeployedHost(host)) {
    window.PORTAL_API_BASE = port === "3000" || port === "" ? "" : "http://" + host + ":3000/api";
    return;
  }
  window.PORTAL_API_BASE = ${JSON.stringify(productionApiBase)};
})();
`;

fs.writeFileSync(apiConfigPath, apiConfigBody);

function pagesFunctionSource(origin) {
  return `const FALLBACK_API_ORIGIN = ${JSON.stringify(origin || "")};

export async function onRequest(context) {
  const origin = String(context.env.RAILWAY_API_URL || FALLBACK_API_ORIGIN || "")
    .trim()
    .replace(/\\/api\\/?$/, "")
    .replace(/\\/$/, "");

  if (!origin) {
    return Response.json({ error: "Portal API origin is not configured." }, { status: 503 });
  }

  const splat = context.params.path;
  const suffix = Array.isArray(splat) ? splat.join("/") : splat || "";
  const incoming = new URL(context.request.url);
  const target = origin + "/api/" + suffix + incoming.search;

  const headers = new Headers(context.request.headers);
  headers.delete("host");
  headers.set("x-forwarded-host", incoming.host);
  headers.set("x-forwarded-proto", incoming.protocol.replace(":", ""));

  const init = {
    method: context.request.method,
    headers,
    redirect: "manual",
  };

  if (context.request.method !== "GET" && context.request.method !== "HEAD") {
    init.body = context.request.body;
    init.duplex = "half";
  }

  const upstream = await fetch(target, init);
  return new Response(upstream.body, {
    status: upstream.status,
    statusText: upstream.statusText,
    headers: upstream.headers,
  });
}
`;
}

const functionDir = path.join(root, "functions", "api");
fs.mkdirSync(functionDir, { recursive: true });
fs.writeFileSync(path.join(functionDir, "[[path]].js"), pagesFunctionSource(railwayOrigin));

const headersBody = `/assets/*
  Cache-Control: public, max-age=2592000, stale-while-revalidate=31536000

/*.js
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800

/*.css
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800

/*.webp
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800

/*.woff2
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800
`;

const routesBody = `${JSON.stringify(
  {
    version: 1,
    include: ["/api/*"],
    exclude: [],
  },
  null,
  2
)}\n`;

function copyPublicSite() {
  fs.rmSync(distDir, { recursive: true, force: true });
  fs.mkdirSync(distDir, { recursive: true });

  for (const name of fs.readdirSync(root)) {
    if (!/\.(html|css|js|txt|xml|ico|webmanifest)$/i.test(name)) continue;
    fs.copyFileSync(path.join(root, name), path.join(distDir, name));
  }

  const assetsSrc = path.join(root, "assets");
  if (fs.existsSync(assetsSrc)) {
    fs.cpSync(assetsSrc, path.join(distDir, "assets"), {
      recursive: true,
      filter: (src) => !src.split(path.sep).includes("originals"),
    });
  }

  const portalSrc = path.join(root, "portal");
  if (fs.existsSync(portalSrc)) {
    fs.cpSync(portalSrc, path.join(distDir, "portal"), { recursive: true });
  }

  fs.writeFileSync(path.join(distDir, "_headers"), headersBody);
  fs.writeFileSync(path.join(distDir, "_routes.json"), routesBody);
}

copyPublicSite();

if (railwayOrigin) {
  console.log(`[deploy] Pages Function /api/* → ${railwayOrigin}/api/*`);
} else {
  console.log("[deploy] No railwayOrigin — local dev uses npm start (/api same origin)");
}

console.log("[deploy] Wrote portal/api-config.js, functions/api/[[path]].js, and dist/");
