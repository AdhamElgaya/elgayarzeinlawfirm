import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function readConfig() {
  const filePath = path.join(root, "deploy.config.json");
  const file = JSON.parse(fs.readFileSync(filePath, "utf8"));
  const fromEnv = String(process.env.RAILWAY_API_URL || process.env.PORTAL_API_BASE || "")
    .trim()
    .replace(/\/api\/?$/, "");

  const fromFile = String(file.railwayOrigin || "")
    .trim()
    .replace(/\/api\/?$/, "")
    .replace(/\/$/, "");

  return (fromEnv || fromFile).replace(/\/$/, "");
}

const railwayOrigin = readConfig();

if (process.env.VERCEL && !railwayOrigin) {
  console.error(
    "Set railwayOrigin in deploy.config.json (then push) or RAILWAY_API_URL on Vercel."
  );
  process.exit(1);
}

const apiConfigPath = path.join(root, "portal", "api-config.js");
fs.writeFileSync(
  apiConfigPath,
  `// Generated by scripts/sync-deploy-config.js — use /api on Vercel (proxied to Railway).
window.PORTAL_API_BASE = "";
`
);

const vercelConfig = {
  $schema: "https://openapi.vercel.sh/vercel.json",
  installCommand: "npm install",
  buildCommand: "node scripts/sync-deploy-config.js",
};

if (railwayOrigin) {
  vercelConfig.rewrites = [
    {
      source: "/api/(.*)",
      destination: `${railwayOrigin}/api/$1`,
    },
  ];
  console.log(`[deploy] Proxy /api/* → ${railwayOrigin}/api/*`);
} else {
  console.log("[deploy] No railwayOrigin — local dev uses npm start (/api same origin)");
}

fs.writeFileSync(path.join(root, "vercel.json"), `${JSON.stringify(vercelConfig, null, 2)}\n`);
console.log("[deploy] Wrote vercel.json and portal/api-config.js");
